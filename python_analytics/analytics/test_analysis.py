def get_total_tests_count(conn: Optional[sqlite3.Connection] = None) -> int:
    """Return the total number of active tests in the catalog."""
    close_conn = conn is None
    if close_conn:
        conn = get_connection()

    try:
        row = conn.execute(
            "SELECT COUNT(*) AS cnt FROM tests WHERE is_active = 1"
        ).fetchone()
        return row["cnt"] if row else 0
    finally:
        if close_conn:
            conn.close()


def get_total_orders_count(conn: Optional[sqlite3.Connection] = None) -> int:
    """Return the total number of orders."""
